// Map.cpp
#include "Map.h"

namespace {
// Легенда:  '.' - пол
//   '1' - кирпич (внешние стены)   '2' - дерево (кабинет)
//   '3' - камень (колонны, библиотека)   '4' - обои (оранжерея)
//   '5' - мебель (стол, шкафы, клумбы) - тоже непроходима
// Комнаты: кабинет (слева вверху), библиотека (по центру), оранжерея (справа),
//          большой холл (внизу). Проёмы-двери в строке 9.
const char* const kLevel[] = {
    "1111111111111111111111111", // 0
    "1.......2.......3.......1", // 1
    "1.......2.......3.......1", // 2
    "1..55...2.......3.......1", // 3
    "1.......2..555..3.......1", // 4
    "1.......2.......3.......1", // 5
    "1.......2.......3..55...1", // 6
    "1.......2.......3.......1", // 7
    "1.......2.......3.......1", // 8
    "1111.1111111.1111111.1111", // 9  (двери в x=4, x=12, x=20)
    "1.......................1", // 10
    "1.......................1", // 11
    "1.....3...........3.....1", // 12
    "1.......................1", // 13
    "1.......................1", // 14
    "1.....3...........3.....1", // 15
    "1.......................1", // 16
    "1.......................1", // 17
    "1111111111111111111111111", // 18
};
}

Map::Map() {
    for (const char* row : kLevel) rows_.emplace_back(row);
    height_ = static_cast<int>(rows_.size());
    width_ = static_cast<int>(rows_[0].size());
}

char Map::Cell(int x, int y) const {
    if (x < 0 || y < 0 || x >= width_ || y >= height_) return '1';
    return rows_[y][x];
}
