Map::Map() { Load(0); }

int Map::LevelCount() { return static_cast<int>(sizeof(kLevels) / sizeof(kLevels[0])); }

void Map::Load(int levelId) {
    if (levelId < 0 || levelId >= LevelCount()) levelId = 0;
    const LevelDef& def = kLevels[levelId];
    rows_.clear();
    for (int i = 0; i < def.rowCount; ++i) rows_.emplace_back(def.rows[i]);
    height_ = static_cast<int>(rows_.size());
    width_ = static_cast<int>(rows_[0].size());
    levelId_ = levelId;
    name_ = def.name;
    startX_ = def.startX;
    startY_ = def.startY;
    startAngle_ = def.startAngle;
}

char Map::Cell(int x, int y) const {
    if (x < 0 || y < 0 || x >= width_ || y >= height_) return '1';
    return rows_[y][x];
}
