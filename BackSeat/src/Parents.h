// ============================================================================
//  Parents.h — родители на передних сиденьях: ссора, реплики, субтитры.
//
//  Родители никогда не замечают монстра. Они спорят между собой (сценарий
//  из заранее написанных «перепалок»), а на некоторые события реагируют
//  отдельными репликами (стук по крыше — «яма, наверное», вспышка камеры —
//  «убери фотоаппарат!», мало бензина и т.д.).
//
//  Модуль ничего не рисует. RealWorldScene берёт отсюда анимационные
//  параметры (кто говорит, поворот головы), Game — субтитры и звук «бубнежа».
// ============================================================================
#pragma once

#include "Common.h"

#include <memory>

enum class Speaker { Dad, Mom };

// Внешние события, на которые родители могут отреагировать.
enum class ParentCue {
    RoofThud,     // что-то тяжёлое ударило по крыше
    WindowBang,   // удар по стеклу (реагируют вяло, списывают на ветер/ветки)
    CameraFlash,  // ребёнок щёлкнул вспышкой в салоне
    LowFuel,      // бензина мало
    ConsoleCrash, // громкий писк консоли
    Stalling,     // двигатель чихает
    NearHome,     // скоро дом
    Arrived,      // приехали
    EndlessLoop,  // бесконечный режим: дорога «повторяется», родителям не по себе
    KidAsleep,    // ребёнок «уснул»: родители сразу становятся странными
    AsleepTalk,   // пока ребёнок «спит»: странные разговоры вместо ссоры
    Whisper,      // безликие шепчут «спящему» (звучит даже после silence())
};

class Parents {
public:
    Parents();
    ~Parents();
    Parents(const Parents&) = delete;
    Parents& operator=(const Parents&) = delete;

    void reset(uint32_t seed);
    void update(float dt);

    // Реакция на событие. Реплики-реакции имеют приоритет над ссорой, но у
    // каждой своя перезарядка, чтобы не повторяться.
    void cue(ParentCue c);

    // Замолчать навсегда (до reset): текущая реплика гаснет, новых не будет —
    // кроме шёпота (ParentCue::Whisper). Используется в бесконечном режиме перед
    // тем, как родители обернутся; имя говорящего тогда — «???».
    void silence();

    // Ребёнок «спит» (притворяется): обычная ссора не начинается, а начатая
    // обрывается после текущей реплики — звучат только реакции.
    void setKidAsleep(bool asleep);

    // ---- Текущая реплика --------------------------------------------------------
    bool hasLine() const;
    Speaker speaker() const;          // кто говорит сейчас
    const char* speakerName() const;  // «ПАПА» / «МАМА» (UTF-8)
    const char* text() const;         // текст реплики (UTF-8), "" если молчат
    int visibleChars() const;         // сколько символов уже «произнесено» (печатная машинка)
    float lineAlpha() const;          // 0..1 — прозрачность субтитра (появление/исчезание)

    // ---- Анимация -----------------------------------------------------------------
    // 0..1 — насколько активно человек говорит прямо сейчас (покачивание головы).
    float talk(Speaker s) const;
    // -1..1 — поворот головы (-1 — к водителю/влево, 1 — вправо, 0 — прямо).
    float headTurn(Speaker s) const;
    // Злость/напряжение ссоры 0..1 (жестикуляция, громкость бубнежа).
    float tension() const;

    // ---- Звук ----------------------------------------------------------------------
    // true один раз в начале каждой новой реплики; who — кто, duration — длительность (с).
    bool takeLineStarted(Speaker& who, float& duration);

private:
    struct State; // всё состояние — в Parents.cpp
    std::unique_ptr<State> st_;
};
